P('    property <bool> wg: !IconClock.reduced && (root.hover || root.wag-always);')
for n in names:
    P('    if root.name == "%s": I-%s { width: root.width; height: root.height; c: root.tint; sw: root.sw; eo: root.eyes-open; bs: root.bs; live: root.live && !IconClock.reduced; flow-active: root.live; ft: root.lt; wt: root.wt; hp: root.hp; wagging: root.wg; }' % (n, n))
