"""Generate ui/icons.slint from the prototype's ICONS map (24x24 stroke icons)."""
import json, math, xml.etree.ElementTree as ET
import svgpath as SP
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path(__file__).resolve().parent / "icon_sources"
parser = argparse.ArgumentParser(description="Check or regenerate native PURR icon and face components.")
parser.add_argument("--write", action="store_true", help="Update generated Slint files; default checks without writing.")
args = parser.parse_args()

def emit(name, body):
    path = ROOT / "src/ui" / name
    if args.write:
        path.write_text(body, encoding="utf8")
    elif not path.exists() or path.read_text(encoding="utf8") != body:
        raise SystemExit(f"{path}: generated content differs; inspect before using --write")


icons = json.load((SOURCE / 'icons.json').open(encoding='utf8'))
f = lambda v: ('%.3f' % v).rstrip('0').rstrip('.') if v != int(v) else str(int(v))

def circle_cmd(cx, cy, r):
    return 'M%s %s A%s %s 0 1 0 %s %s A%s %s 0 1 0 %s %s Z' % (f(cx-r), f(cy), f(r), f(r), f(cx+r), f(cy), f(r), f(r), f(cx-r), f(cy))

def walk(el, classes, rot, out):
    for ch in el:
        tag = ch.tag.split('}')[-1]
        cl = classes | set((ch.get('class') or '').split())
        r = rot
        tr = ch.get('transform')
        if tr and tr.startswith('rotate('):
            a = [float(v) for v in tr[7:-1].replace(',', ' ').split()]
            r = (a[0], a[1], a[2])
        if tag == 'g':
            walk(ch, cl, r, out)
        elif tag == 'path':
            segs = SP.parse(ch.get('d'))
            out.append(dict(kind='path', segs=segs, cmd=SP.to_abs_string(segs), cls=cl, rot=r,
                            fill=('f' in cl) or ch.get('fill') == 'currentColor'))
        elif tag == 'circle':
            cx, cy, rr = float(ch.get('cx')), float(ch.get('cy')), float(ch.get('r'))
            out.append(dict(kind='circle', c=(cx, cy, rr), cmd=circle_cmd(cx, cy, rr), cls=cl, rot=r,
                            fill=('f' in cl) or ch.get('fill') == 'currentColor',
                            bb=(cx-rr, cy-rr, cx+rr, cy+rr)))

def group_bbox(parts):
    xs = []; ys = []
    for p in parts:
        bb = p['bb'] if p['kind'] == 'circle' else SP.bbox(p['segs'])
        xs += [bb[0], bb[2]]; ys += [bb[1], bb[3]]
    return (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2

ANIM = ['ear', 'head', 'p2', 'thread', 'tail', 'peek', 'w1', 'w2']
lines = []
P = lines.append
P('// Generated by tools/gen_icons.py from the PURR v5 prototype icon set. Do not edit by hand.')
P('import { Theme, IconClock } from "tokens.slint";\nimport { Anim } from "animation.slint";')
P('')
for name, frag in icons.items():
    root = ET.fromstring('<svg xmlns="http://www.w3.org/2000/svg">' + frag + '</svg>')
    parts = []; walk(root, set(), None, parts)
    # transform origins: per animated class, bbox of all parts sharing that class (fill-box of the group)
    origins = {}
    for a in ANIM:
        grp = [p for p in parts if a in p['cls']]
        if grp:
            # each element animates around its own box; for groups (p2) the group box
            origins[a] = group_bbox(grp)
    P('component I-%s inherits Rectangle {' % name)
    P('    in property <color> c; in property <length> sw; in property <bool> eo; in property <float> bs: 1;')
    P('    in property <bool> live; in property <bool> flow-active; in property <float> ft; in property <float> wt; in property <float> hp: 99999; in property <bool> wagging;')
    P('    property <float> k: self.width / 1px / 24;')
    for p in parts:
        cl = p['cls']
        if 'sz' in cl: continue          # only visible inside a pressed-off toggle; never used that way
        props = []
        vis = None
        if 'e-s' in cl: vis = '!root.eo'
        if 'e-o' in cl: vis = 'root.eo'
        if p['fill']:
            props += ['fill: root.c;']
        else:
            props += ['stroke: root.c;', 'stroke-width: root.sw;', 'stroke-line-cap: round;', 'stroke-line-join: round;']
        # commands
        if 'e-o' in cl and p['kind'] == 'circle':
            cx, cy, r = p['c']
            cmd = ('"M%s %s A%s " + (%s * root.bs) + " 0 1 0 %s %s A%s " + (%s * root.bs) + " 0 1 0 %s %s Z"'
                   % (f(cx-r), f(cy), f(r), f(r), f(cx+r), f(cy), f(r), f(r), f(cx-r), f(cy)))
        else:
            cmd = '"%s"' % p['cmd']
        tx = ty = '0'
        rot = None; ox = oy = None
        opac = None
        if p['rot']:
            rot = f(p['rot'][0]); ox, oy = p['rot'][1], p['rot'][2]
        for a in ('ear', 'head'):
            if a in cl:
                ox, oy = origins[a]; rot = 'Anim.twitch-rot(root.hp)'; ty = 'Anim.twitch-ty(root.hp)'
        if 'p2' in cl:
            tx = 'Anim.hop(root.hp)'; ty = '(-1.5 * Anim.hop(root.hp))'
        for a in ('thread', 'tail'):
            if a in cl:
                ox, oy = origins[a]; rot = '(root.wagging ? Anim.wag(root.wt) : 0)'
        if 'peek' in cl: opac = 'Anim.peek(root.hp)'
        if 'w1' in cl: opac = 'root.live ? Anim.pulse(root.ft, 0) : 1'
        if 'w2' in cl: opac = 'root.live ? Anim.pulse(root.ft, 600) : 1'
        if rot:
            segs = p['segs'] if p['kind'] == 'path' else SP.parse(p['cmd'])
            cmd = SP.slint_rotated(segs, rot, ox, oy, ty, blink='e-o' in cl)
            ty = '0'
        geo = ('x: %s * root.k * 1px - self.stroke-width / 2; y: %s * root.k * 1px - self.stroke-width / 2; width: root.width + self.stroke-width; height: root.height + self.stroke-width; '
               'viewbox-x: 0; viewbox-y: 0; viewbox-width: 24; viewbox-height: 24;' % (tx, ty))
        extra = []
        if vis: extra.append('visible: %s;' % vis)
        if opac: extra.append('opacity: %s;' % opac)
        if 'flow' in cl:
            # marching dashes (stroke-dasharray 2.6 2.2, offset 0 -> -4.8 over .9s) pre-baked into frames
            poly = SP.flatten(p['segs'], 40)[0]
            frames = []
            NF = 60
            for i in range(NF):
                ph = -4.8 * i / NF  # pattern phase at path start
                dl = SP.dash(poly, 2.6, 2.2, ph % 4.8)
                frames.append(' '.join('M' + ' L'.join('%s %s' % (f(round(x, 2)), f(round(y, 2))) for x, y in d) for d in dl))
            P('    Path { %s %s commands: "%s"; visible: !root.flow-active; }' % (geo, ' '.join(props), p['cmd']))
            P('    Path { %s %s visible: root.flow-active; commands: [%s][Math.mod(Math.floor(root.ft / 900 * %d), %d)]; }'
              % (geo, ' '.join(props), ', '.join('"%s"' % fr for fr in frames), NF, NF))
            continue
        P('    Path { %s %s %s commands: %s; }' % (geo, ' '.join(props), ' '.join(extra), cmd))
    P('}')
    P('')

names = list(icons.keys())
